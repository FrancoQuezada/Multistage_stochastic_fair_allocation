# =====================================================================================
# Manifest-driven campaign shard runner (redesign stage 13).
#
# Runs one deterministic stride of the campaign's tasks, serially, into an isolated shard root.
# Concurrency comes from launching this entry point several times with different shard indices;
# there is NO Julia coordinator and no shared cursor, which is what makes the processes safe to
# run against the same shard root.
#
#     OOS_SHARD_INDEX=1 OOS_SHARDS=8 bash scripts/oos/run_oos_task.sh
#
# The task list is enumerated from the saved structural manifest and cross-checked against the
# identifiers the manifest recorded, so a campaign cannot silently run a different catalog than
# the one that was generated and validated.
#
# REQUIRED:
#     STRUCTURAL_MANIFEST_PATH   the manifest generated by stage 3
#     FORMULATION_ID             campaign formulation identifier
#     OOS_SHARD_ROOT             directory the shards are committed under
#
# Optional:
#     OOS_SHARD_INDEX / OOS_SHARDS     stride partition, default 1 of 1
#     OOS_REPLICATIONS                 R override; default is the manifest's own count
#     CONTROLLER_SET / FAIRNESS_SET    comma-separated, default the full campaign sets
#     SOLVER_TIME_LIMIT_SEC, PEA_TOLERANCE_MODE, MULTISTAGE_BRANCHING, TWO_STAGE_SCENARIOS
#     OOS_SOLVER_THREADS               CPLEX threads per shard, default 1 (see section 4.9)
#     SOLVER_MIP_GAP                   relative MIP gap, default 1e-6 (see solver_mip_gap)
#     GRID_DIRECTION_EXCLUSIVITY       household import/export exclusivity binary, default 1
#     BATTERY_DIRECTION_EXCLUSIVITY    shared-battery mode binary vs [0,1] relaxation, default 1
#     OOS_WORKER                       recorded in the execution provenance, never in the science
# =====================================================================================

const REPO_ROOT = normpath(joinpath(@__DIR__, "..", ".."))
include(joinpath(REPO_ROOT, "codes", "oos_experiment", "oos_experiment.jl"))

function _need(name::AbstractString, description::AbstractString)
    raw = strip(get(ENV, String(name), ""))
    isempty(raw) && error("Falta la entrada obligatoria $name ($description).")
    return String(raw)
end

_opt(name, fallback) = let raw = strip(get(ENV, String(name), ""))
    isempty(raw) ? fallback : String(raw)
end
_opt_int(name, fallback) = let raw = _opt(name, "")
    isempty(raw) ? fallback : parse(Int, raw)
end
_opt_float(name, fallback) = let raw = _opt(name, "")
    isempty(raw) ? fallback : parse(Float64, raw)
end
_opt_list(name) = [String(strip(x)) for x in split(_opt(name, ""), ',') if !isempty(strip(x))]

function main()
    manifest_path = _need("STRUCTURAL_MANIFEST_PATH", "manifiesto estructural de la campaña")
    shard_root = _need("OOS_SHARD_ROOT", "raíz de shards de la campaña")
    formulation = _need("FORMULATION_ID", "identificador de formulación")

    shard_index = _opt_int("OOS_SHARD_INDEX", 1)
    shards = _opt_int("OOS_SHARDS", 1)
    1 <= shard_index <= shards ||
        error("OOS_SHARD_INDEX=$shard_index fuera de rango para OOS_SHARDS=$shards.")

    replications = _opt_int("OOS_REPLICATIONS", 0)
    enumeration = oos_tasks_from_manifest(
        manifest_path; replications=replications > 0 ? replications : nothing,
    )
    design = enumeration.design

    controllers = _opt_list("CONTROLLER_SET")
    policies = _opt_list("FAIRNESS_SET")
    # [2, 2] matches OOSExperimentConfig's own keyword default (types.jl) and
    # oos_config_from_environment's default (oos_experiment.jl), so an operator who omits
    # MULTISTAGE_BRANCHING gets the same look-ahead tree shape from every entry point.
    multistage_branching, multistage_periods_per_stage = _env_multistage_tree([2, 2])

    # Non-structural settings only. Every instance-level field is overridden per structural
    # instance by `materialize_structural_instance`, from the manifest's own design.
    base_config = OOSExperimentConfig(
        experiment_seed=design.experiment_seed,
        # The manifest's own planned R, UNLESS this run explicitly overrides it (a partial-R
        # pilot): metadata must record what this shard set actually covers, not the catalog's
        # original plan, or every shard's experiment_config.json would claim a replication count
        # larger than what was actually simulated.
        oos_replications=(replications > 0 ? replications : design.oos_replications),
        evaluation_horizon=design.evaluation_horizon,
        lookahead_horizon=design.lookahead_horizon,
        implementation_step=design.implementation_step,
        formulation_id=formulation,
        multistage_branching=multistage_branching,
        multistage_periods_per_stage=multistage_periods_per_stage,
        two_stage_scenarios=_opt_int("TWO_STAGE_SCENARIOS", 16),
        solver_time_limit_sec=_opt_float("SOLVER_TIME_LIMIT_SEC", 600.0),
        # ONE CPLEX thread per shard, set as a solver attribute rather than an environment
        # variable: CPLEX's API does not read `CPXPARAM_Threads` from the environment, so the
        # shell export alone left every shard using the whole machine. Plan section 4.9 fixes
        # this to one per worker and section 12 records it as not open, so the default belongs
        # here, where it actually binds.
        solver_threads=_opt_int("OOS_SOLVER_THREADS", 1),
        solver_mip_gap=_opt_float("SOLVER_MIP_GAP", 1e-6),
        pea_tolerance_mode=Symbol(_opt("PEA_TOLERANCE_MODE", "adaptive_minimum")),
        # Reuse `_env_bool` from oos_experiment.jl (included above): before this fix, this
        # explicit keyword list silently omitted both flags, so every shard of the parallel
        # campaign always fell back to the compile-time struct default (`true`) regardless of
        # what a caller exported.
        grid_direction_exclusivity=_env_bool("GRID_DIRECTION_EXCLUSIVITY", true),
        battery_direction_exclusivity=_env_bool("BATTERY_DIRECTION_EXCLUSIVITY", true),
        export_representative_models=false,
        require_shared_battery_validation=false,
        instance_file=absolute_base_instance_file(first(design.base_instance_files)),
        households=design.households,
        theta=uncertainty_theta(design, LOW_UNCERTAINTY),
        avg_demand=design.avg_demand,
        dev_demand=design.dev_demand,
        pv_scale=design.pv_scale,
        demand_profile=design.repository_demand_profile,
        in_sample_stages=design.in_sample_stages,
        in_sample_children=design.in_sample_children,
        in_sample_periods_per_stage=design.in_sample_periods_per_stage,
        (isempty(controllers) ? () :
         (; controller_set=[parse_controller_kind(c) for c in controllers]))...,
        (isempty(policies) ? () :
         (; fairness_set=[parse_fairness_policy(f) for f in policies]))...,
    )

    mine = tasks_for_shard(enumeration.tasks, shard_index, shards)

    println("=== Shard $shard_index de $shards ===")
    println("manifiesto      : ", manifest_path)
    println("manifest_id     : ", enumeration.manifest_id)
    println("catálogo        : ", length(enumeration.specs), " instancias estructurales")
    println("réplicas (R)    : ", replications > 0 ? replications : design.oos_replications,
            replications > 0 ? "  [override del manifiesto]" : "")
    println("tareas totales  : ", length(enumeration.tasks))
    println("tareas de este  : ", length(mine))
    println("shard root      : ", shard_root)
    println("hilos CPLEX     : ", base_config.solver_threads, " (atributo del solver)")
    println("gap MIP         : ", base_config.solver_mip_gap,
            "  (~", round(base_config.solver_mip_gap * 283847, digits=2),
            " unidades de costo por solve, frente a un efecto mínimo de ~337)")
    println("H=", design.evaluation_horizon, " L=", design.lookahead_horizon,
            " h=", design.implementation_step,
            " inicios=", rolling_iteration_starts(design))
    println()

    worker = _opt_int("OOS_WORKER", shard_index)
    for (position, task) in enumerate(mine)
        println("[$position/$(length(mine))] ", task.task_id)
        digest = run_oos_task(base_config, task; shard_root=shard_root, worker=worker,
                              verbose=true)
        println("    digest=", digest)
    end

    println()
    println("OOS_SHARD_INDEX=", shard_index)
    println("OOS_SHARD_TASKS=", length(mine))
    println("OOS_SHARD_ROOT=", shard_root)
    println("Este shard terminó. La campaña no está completa hasta que los ",
            length(enumeration.tasks), " task_id estén comprometidos y el merge los acepte.")
end

main()
